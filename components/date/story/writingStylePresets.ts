/**
 * 根据用户当前 writingStyle 文本,反推是哪个预设(用于回显)
 * - 完全匹配 preset.prompt → 返回 preset.id
 * - 不匹配 → 返回 null(用户手写)
 */
export function matchWritingStylePreset(text: string): string | null {
    if (!text) return null;
    const trimmed = text.trim();
    const found = WRITING_STYLE_PRESETS.find(p => p.prompt === trimmed);
    return found ? found.id : null;
}
